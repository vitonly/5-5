/* ---------- Помощники ---------- */

const str = (w: Workbook, id: string) => String(w[id] ?? "").trim();
const low = (w: Workbook, id: string) => str(w, id).toLowerCase();
const len = (w: Workbook, id: string) => str(w, id).length;
const zv = (w: Workbook, g: number, f: number) => str(w, `z${g}_${f}`);
/** Только цифры из строки: «50 000 ₽» → 50000 */
export const digits = (s: string) => Number(String(s).replace(/[^\d]/g, "")) || 0;

/** Все числа из текста: «50 000», «50000», «50 тыс.» → 50000 */
export function numbers(t: string): number[] {
  const out: number[] = [];
  String(t || "").replace(/(\d[\d\s ]*\d|\d)(\s*(тыс\.?|тысяч\S*|k|к))?/gi, (m, n: string, _x, k) => {
    let v = Number(n.replace(/[\s ]/g, ""));
    if (k) v *= 1000;
    out.push(v);
    return m;
  });
  return out;
}
const money = (t: string) => numbers(t).filter((v) => v >= 1000);
/** Число перед словом: «8 команд» → 8 */
function before(t: string, word: string): number | null {
  const m = String(t || "").toLowerCase().match(new RegExp("(\\d+)\\s*(?:\\S+\\s)?" + word));
  return m ? Number(m[1]) : null;
}
/** Время только через двоеточие (10:00), чтобы дата 20.03 не считалась временем */
const times = (t: string) => (String(t || "").match(/\b([01]?\d|2[0-3]):[0-5]\d\b/g) || []).map((x) => x.padStart(5, "0"));

export function smetaSum(w: Workbook) {
  return A_SMETA.reduce((a, _, i) => a + (Number(w[`sm${i}`]) || 0), 0);
}

/** Название команды по посеву */
export function teamName(w: Workbook, seed: number) {
  return str(w, `seed${seed}`) || `Команда ${seed}`;
}

type Side = { seed: number } | { from: string };
export function sideName(w: Workbook, side: Side): string {
  if ("seed" in side) return teamName(w, side.seed);
  return winnerName(w, side.from);
}
export function winnerName(w: Workbook, matchId: string): string {
  const m = A_MATCHES.find((x) => x.id === matchId)!;
  const pick = w[`${matchId}w`];
  if (pick === "a") return sideName(w, m.a);
  if (pick === "b") return sideName(w, m.b);
  return `Победитель ${m.label.toLowerCase().replace("матч", "матча")}`;
}

/* ---------- Разбор ---------- */

export type ReviewCard = { title: string; max: string; good: string[]; bad: string[] };

/** Проверка заявки: пустые поля и цифры против вводной и сметы */
export function checkApplication(w: Workbook): string[] {
  const msgs: string[] = [];
  const empty = A_FORM.flatMap(([, f], g) => f.map((_, i) => `z${g}_${i}`)).filter((id) => !str(w, id));
  if (empty.length) msgs.push(`Пустых полей: ${empty.length} — за «все поля заполнены» будет 0.`);
  if (zv(w, 2, 0) && digits(zv(w, 2, 0)) !== A_BRIEF.teams) msgs.push("Количество команд не 8 — не совпадает с вводной и сеткой.");
  if (zv(w, 2, 1) && digits(zv(w, 2, 1)) < 40) msgs.push("Участников меньше 40: 8 команд × 5 игроков = минимум 40 (с запасными больше).");
  if (zv(w, 3, 0) && digits(zv(w, 3, 0)) < A_BRIEF.pcs) msgs.push("Рабочих мест меньше 20: чтобы играть два матча одновременно, нужно 2 × 10 ПК.");
  const prize = Number(w.sm1) || 0;
  if (zv(w, 2, 4) && prize && digits(zv(w, 2, 4)) !== prize) {
    msgs.push(`Призовой фонд в заявке (${zv(w, 2, 4)}) не совпадает со сметой (${prize.toLocaleString("ru-RU")} ₽).`);
  }
  if (zv(w, 0, 3) && !A_BRIEF.dateWords.test(zv(w, 0, 3).toLowerCase())) msgs.push("Проверь дату: по вводной турнир 20 марта 2027.");
  return msgs;
}

/** Сверка цифр между регламентом, сеткой, презентацией, сметой и заявкой */
export function crossCheck(w: Workbook): ReviewCard {
  const c: ReviewCard = { title: "Сверка между файлами", max: "", good: [], bad: [] };
  const regAll = A_REG.map((x) => str(w, x.id)).join("\n");

  // 1. Призовой фонд
  const prizeSmeta = Number(w.sm1) || 0;
  const r5 = money(str(w, "r5"));
  const prizeReg = r5.length ? Math.max(...r5) : 0;
  const prizeZ = money(zv(w, 2, 4))[0] || numbers(zv(w, 2, 4))[0] || 0;
  const vals = ([["регламенте", prizeReg], ["смете", prizeSmeta], ["заявке", prizeZ]] as [string, number][]).filter((x) => x[1]);
  if (vals.length < 2) c.bad.push("Призовой фонд нельзя сверить: он указан меньше чем в двух местах (регламент, смета, заявка).");
  else if (new Set(vals.map((x) => x[1])).size === 1) c.good.push(`Призовой фонд одинаковый везде: ${vals[0][1].toLocaleString("ru-RU")} ₽.`);
  else c.bad.push("Призовой фонд расходится: " + vals.map((x) => `в ${x[0]} ${x[1].toLocaleString("ru-RU")} ₽`).join(", ") + ".");
  if (r5.length >= 3) {
    const parts = r5.filter((v) => v !== prizeReg);
    const sum = parts.reduce((a, b) => a + b, 0);
    // «3–4 места по 5 000» — одно число на два места: допускаем оба варианта
    const sumAlt = sum + (/(3\s*[-–]\s*4|по\s*\d)/i.test(str(w, "r5")) ? Math.min(...parts) : 0);
    if (sum === prizeReg || sumAlt === prizeReg) c.good.push("Призы по местам в сумме дают общий призовой фонд.");
    else c.bad.push(`Призы по местам (${parts.map((v) => v.toLocaleString("ru-RU")).join(" + ")}) не складываются в общий фонд ${prizeReg.toLocaleString("ru-RU")} ₽.`);
  }

  // 2. Итог сметы на слайде
  const total = smetaSum(w);
  const slide5 = money(`${str(w, "s5h")} ${str(w, "s5b")}`);
  if (total && slide5.length && !slide5.includes(total)) {
    c.bad.push(`На слайде «Смета» есть суммы (${slide5.map((v) => v.toLocaleString("ru-RU")).join(", ")}), но нет итога сметы ${total.toLocaleString("ru-RU")} ₽.`);
  }

  // 3. Команды
  const tv = ([
    ["регламенте", before(regAll, "команд")],
    ["презентации", before(`${str(w, "s4h")} ${str(w, "s4b")}`, "команд")],
    ["заявке", digits(zv(w, 2, 0)) || null],
  ] as [string, number | null][]).filter((x) => x[1]);
  const tBad = tv.filter((x) => x[1] !== A_BRIEF.teams);
  if (!tv.length) c.bad.push("Количество команд не найдено ни в регламенте, ни в презентации, ни в заявке.");
  else if (tBad.length) c.bad.push("Количество команд не 8: " + tBad.map((x) => `в ${x[0]} ${x[1]}`).join(", ") + ".");
  else c.good.push(`8 команд — одинаково в ${tv.map((x) => x[0]).join(", ")}.`);

  // 4. Участники = 8 × (основные + запасные)
  const main = before(str(w, "r2"), "основн") || 5;
  const subs = before(str(w, "r2"), "запасн");
  const pZ = digits(zv(w, 2, 1));
  if (subs !== null && pZ) {
    const need = A_BRIEF.teams * (main + subs);
    if (pZ === need) c.good.push(`Участников в заявке ${pZ} = 8 команд × (${main} + ${subs} запасных) из регламента.`);
    else c.bad.push(`В регламенте состав ${main} + ${subs} запасных, значит участников 8 × ${main + subs} = ${need}, а в заявке ${pZ}.`);
  } else if (pZ) c.bad.push("В регламенте не указано число запасных цифрой — нельзя сверить количество участников с заявкой.");

  // 5. Дата
  const dMiss = ([["регламенте", regAll], ["титульном слайде", `${str(w, "s1h")} ${str(w, "s1b")}`], ["заявке", zv(w, 0, 3)]] as [string, string][])
    .filter((x) => !A_BRIEF.dateWords.test(x[1].toLowerCase()))
    .map((x) => x[0]);
  if (dMiss.length) c.bad.push("Дата 20 марта не найдена в: " + dMiss.join(", ") + ".");
  else c.good.push("Дата 20 марта одинаковая в регламенте, презентации и заявке.");

  // 6. Время матчей: сетка ↔ расписание
  const rt = new Set(times(str(w, "r4")));
  const gridT = A_MATCHES.map((m) => [m.label, times(str(w, `${m.id}t`))[0]] as [string, string | undefined]).filter((x) => x[1]);
  if (gridT.length && rt.size) {
    const miss = gridT.filter((x) => !rt.has(x[1]!));
    if (miss.length) c.bad.push("Время в сетке не совпадает с расписанием в регламенте: " + miss.map((x) => `${x[0]} в ${x[1]}`).join(", ") + ".");
    else c.good.push("Время всех матчей в сетке совпадает с расписанием в регламенте.");
  } else c.bad.push("Нельзя сверить время: нужно время и в сетке, и в расписании регламента (в формате 10:00).");

  // 7. Система проведения
  const sys = (t: string) => {
    const s = t.toLowerCase();
    return /double|двойн/.test(s) ? "double" : /round|кругов/.test(s) ? "round" : /single|олимпийск|одно\S* выбыв/.test(s) ? "single" : null;
  };
  const sR = sys(str(w, "r3"));
  const sZ = sys(zv(w, 2, 2));
  if (sR && sZ) {
    if (sR === sZ) c.good.push("Система проведения в заявке та же, что в регламенте.");
    else c.bad.push("Система проведения в заявке не та, что в регламенте.");
  }

  // 8. Платформа трансляции
  const plat = (t: string) => {
    const s = t.toLowerCase();
    return ["vk", "twitch", "youtube", "rutube", "trovo"].filter((x) => s.includes(x) || (x === "vk" && /вк\b|вконтакт/.test(s)));
  };
  const pR = plat(str(w, "r8"));
  const pZz = plat(zv(w, 4, 1));
  if (pR.length && pZz.length) {
    if (pZz.every((x) => pR.includes(x))) c.good.push("Платформа трансляции в заявке совпадает с регламентом.");
    else c.bad.push(`Платформа трансляции: в регламенте ${pR.join(", ")}, в заявке ${pZz.join(", ")}.`);
  }

  // 9. Игровые дни
  if (zv(w, 2, 3) && digits(zv(w, 2, 3)) !== 1) c.bad.push(`По вводной турнир идёт один день, а в заявке игровых дней ${zv(w, 2, 3)}.`);
  return c;
}

/** Части тетради модуля А */
export type APart = "reg" | "grid" | "pres" | "app";
export const A_ALL_PARTS: APart[] = ["reg", "grid", "pres", "app"];

/** Разбор: регламент, сетка, презентация, заявка; сверка между файлами — только когда заполнены все части */
export function reviewWorkbook(w: Workbook, parts: APart[] = A_ALL_PARTS): ReviewCard[] {
  return reviewAll(w).filter((c) =>
    c.title === "Регламент" ? parts.includes("reg")
    : c.title === "Сетка" ? parts.includes("grid")
    : c.title === "Презентация" ? parts.includes("pres")
    : c.title === "Заявка" ? parts.includes("app")
    : parts.length === A_ALL_PARTS.length
  );
}

function reviewAll(w: Workbook): ReviewCard[] {
  const all = `${A_REG.map((x) => low(w, x.id)).join(" ")} ${low(w, "norm")}`;
  const R: ReviewCard[] = [];

  // Регламент
  const reg: ReviewCard = { title: "Регламент", max: "3,5", good: [], bad: [] };
  const mustOk = A_REG.filter((x) => x.must && len(w, x.id) >= 150);
  if (mustOk.length === 5) reg.good.push("Обязательные разделы написаны: 5 из 5.");
  else reg.bad.push(`Обязательные разделы написаны: ${mustOk.length} из 5 — не хватает: ${A_REG.filter((x) => x.must && len(w, x.id) < 150).map((x) => `«${x.title.slice(3)}»`).join(", ")}. Без всех пяти теряется 1 балл.`);
  const rule = (ok: boolean, good: string, bad: string) => (ok ? reg.good.push(good) : reg.bad.push(bad));
  rule(/329/.test(all), "Есть ссылка на закон № 329-ФЗ.", "Нет ссылки на закон № 329-ФЗ «О физической культуре и спорте» — добавь в п. 1.2.");
  rule(/(№\s*22|n\s*22|22\.01\.2020|правил[аы] вида спорта)/.test(all), "Есть ссылка на правила вида спорта (приказ № 22).", "Нет ссылки на правила вида спорта «компьютерный спорт» (приказ Минспорта от 22.01.2020 № 22).");
  rule(/554/.test(all), "Упомянут приказ № 554 из задания.", "Нет приказа № 554 (федеральный стандарт по компьютерному спорту) — его номер стоит в задании.");
  rule(/боев\S* арен/.test(all), "Дисциплина названа правильно — «боевая арена».", "Не указана дисциплина «боевая арена» (так Dota 2 называется в правилах вида спорта).");
  rule(/фкс|федераци\S* компьютерного спорта/.test(low(w, "r1")), "Организатор — ФКС России.", "В «Общих положениях» не назван организатор — ФКС России.");
  rule(/(16|шестнадцат)/.test(low(w, "r2")) && /25/.test(low(w, "r2")), "Возраст участников 16–25 совпадает с вводной.", "В «Участниках» нет возраста 16–25 из вводной.");
  rule(/(потому|так как|поскольку|позволяет|чтобы)/.test(low(w, "r3")), "Формат обоснован — это требование для оценки «3».", "Формат не обоснован: напиши, почему Single Elimination (один день, 8 команд, бюджет).");
  rule(/1\s*[-–]\s*8/.test(low(w, "r3")) || /посев/.test(low(w, "r3")), "Описан посев.", "Не описан посев (пары 1–8, 4–5, 3–6, 2–7, как определяется).");
  rule(/bo\s*3|бо\s*3|до двух побед/.test(low(w, "r3")), "Указан формат финала (Bo3).", "Не указан формат матчей по этапам (ЧФ и ПФ Bo1, финал Bo3).");
  rule(/резерв/.test(low(w, "r4")), "В расписании есть резерв времени.", "В расписании нет резерва — без него оценка за качество не поднимется выше «2».");
  rule(/\d{1,2}:\d{2}/.test(str(w, "r4")), "Расписание по времени.", "В расписании нет конкретного времени (10:00, 11:30…).");
  rule(/(1|перв)\S*\s*мест/.test(low(w, "r5")), "Призы расписаны по местам.", "Призовой фонд не расписан по местам (1 место — …, 2 место — …).");
  rule(len(w, "r6") >= 150, "Есть санкции.", "Нет раздела с санкциями (лестница: предупреждение → потеря карты → техпоражение → дисквалификация).");
  rule(/(ставк|пари)/.test(low(w, "r6")), "Есть запрет ставок на матчи.", "В правилах поведения нет запрета ставок на матчи турнира (ст. 26.2 закона № 329-ФЗ).");
  rule(len(w, "r7") >= 120, "Описан порядок при технических сбоях.", "Не описано, что делать при технических сбоях (техпауза, переигровка).");
  R.push(reg);

  // Сетка
  const br: ReviewCard = { title: "Сетка", max: "2", good: [], bad: [] };
  const named = [1, 2, 3, 4, 5, 6, 7, 8].filter((i) => str(w, `seed${i}`)).length;
  if (named === 8) br.good.push("Все 8 команд названы.");
  else br.bad.push(`Названы ${named} команд из 8.`);
  br.good.push("Пары по посеву правильные (1–8, 4–5, 3–6, 2–7) — их собрала программа. На чемпионате расставляешь сам.");
  const timed = A_MATCHES.filter((m) => str(w, `${m.id}t`)).length;
  if (timed === 7) br.good.push("У всех 7 матчей есть время.");
  else br.bad.push(`Время указано у ${timed} матчей из 7 — для «3» нужны даты и время у каждого.`);
  if (w.m7w) br.good.push("Сетка доведена до чемпиона.");
  else br.bad.push("Не выбран победитель финала — сетка не закончена.");
  R.push(br);

  // Презентация
  const pr: ReviewCard = { title: "Презентация", max: "6,5", good: [], bad: [] };
  const filled = A_SLIDES.filter((x) => len(w, `${x.id}b`) + len(w, `${x.id}h`) > 20).length;
  if (filled >= 5) pr.good.push(`Слайдов с содержанием: ${filled} — не меньше 5.`);
  else pr.bad.push(`Слайдов с содержанием: ${filled} — нужно не меньше 5, иначе минус 0,5.`);
  if (/(участник|№)/i.test(`${str(w, "s1h")}${str(w, "s1b")}`)) pr.good.push("На титуле есть номер участника.");
  else pr.bad.push("На титуле нет «Участник № __» — минус 0,5.");
  const sum = smetaSum(w);
  if (sum > 0 && sum <= A_BRIEF.budget) pr.good.push(`Смета: ${sum.toLocaleString("ru-RU")} ₽ — в бюджете.`);
  else if (sum > A_BRIEF.budget) pr.bad.push(`Смета ${sum.toLocaleString("ru-RU")} ₽ больше бюджета 200 000 ₽.`);
  else pr.bad.push("Смета не заполнена.");
  if (Number(w.sm6) > 0) pr.good.push("В смете есть резерв на непредвиденные.");
  else pr.bad.push("В смете нет резерва на непредвиденные (≈10 %).");
  if (len(w, "s6b") >= 60) pr.good.push("Риски расписаны.");
  else pr.bad.push("Слайд с рисками пустой — делай и смету, и риски.");
  if (/\d/.test(str(w, "s7b"))) pr.good.push("Прогноз охвата в цифрах.");
  else pr.bad.push("Нет прогноза медийного охвата в цифрах — это требование для «3» по содержательности.");
  if (/\d/.test(str(w, "s9b"))) pr.good.push("Ожидаемые результаты измеримые.");
  else pr.bad.push("Ожидаемые результаты без цифр.");
  if (len(w, "s3b") >= 80) pr.good.push("ЦА расписана.");
  else pr.bad.push("ЦА расписана слишком коротко: возраст, кто они, где сидят, почему придут.");
  R.push(pr);

  // Заявка
  const zz: ReviewCard = { title: "Заявка", max: "2", good: [], bad: [] };
  const zm = checkApplication(w);
  if (zm.length) zz.bad.push(...zm);
  else zz.good.push("Все поля заполнены, цифры сходятся с вводной, сеткой и сметой.");
  R.push(zz);

  R.push(crossCheck(w));
  return R;
}

/** Работа текстом — тренеру и для переноса в Word */
export function workbookText(w: Workbook): string {
  return [
    "ПОЛОЖЕНИЕ о проведении любительского турнира «Кубок Профессионалов» по компьютерному спорту (дисциплина Dota 2)",
    "",
    ...A_REG.flatMap((s) => [s.title, str(w, s.id) || "(не написано)", ""]),
    "Сетка (Single Elimination, 8 команд):",
    ...A_MATCHES.map((m) => `${m.label} (${m.round}, ${m.bo}) ${str(w, `${m.id}t`) || "время не указано"}: ${sideName(w, m.a)} — ${sideName(w, m.b)} → ${w[`${m.id}w`] ? winnerName(w, m.id) : "?"}`),
    "",
    "Презентация для спонсора:",
    ...A_SLIDES.flatMap((s) => [
      `${s.t}: ${str(w, `${s.id}h`) || "(без заголовка)"}`,
      str(w, `${s.id}b`) || "(пусто)",
      ...(s.smeta ? [...A_SMETA.map((r, i) => `  ${r}: ${str(w, `sm${i}`) || "—"} ₽`), `  Итого: ${smetaSum(w).toLocaleString("ru-RU")} ₽`] : []),
      "",
    ]),
    "ЗАЯВКА на проведение киберспортивного мероприятия",
    ...A_FORM.flatMap(([g, fields], gi) => [g, ...fields.map((f, fi) => `  ${f}: ${zv(w, gi, fi) || "(пусто)"}`)]),
  ].join("\n");
}

export function parseWorkbook(raw: string | null | undefined): Workbook {
  try {
    const data = JSON.parse(raw || "{}");
    return data && typeof data === "object" && !Array.isArray(data) ? (data as Workbook) : {};
  } catch {
    return {};
  }
}
