/** Все вопросы, на которые нужно отвечать (таблица-условие — не вопрос) */
export const DIAG_ITEMS = DIAG_SECTIONS.flatMap((s) => s.items.filter((i) => i.t !== "table"));

/** Ответы: номер варианта, список номеров, текст или шкала «навык → 0..3» */
export type DiagAnswer = number | number[] | string | Record<string, number>;
export type DiagAnswers = Record<string, DiagAnswer>;

/** Отвечен ли вопрос (для счётчика прогресса) */
export function isDiagAnswered(item: DiagItem, v: DiagAnswer | undefined): boolean {
  if (v == null) return false;
  if (item.t === "multi") return Array.isArray(v) && v.length > 0;
  if (item.t === "scale") return typeof v === "object" && !Array.isArray(v) && item.rows.every(([k]) => (v as Record<string, number>)[k] != null);
  if (item.t === "single") return typeof v === "number";
  return String(v).trim().length > 0;
}

/** Оставить в присланных ответах только известные вопросы и правильные типы — защита от мусора */
export function cleanDiagAnswers(raw: unknown): DiagAnswers {
  const out: DiagAnswers = {};
  if (!raw || typeof raw !== "object") return out;
  const src = raw as Record<string, unknown>;
  for (const it of DIAG_ITEMS) {
    const v = src[it.id];
    if (v == null) continue;
    if (it.t === "single" && Number.isInteger(v) && (v as number) >= 0 && (v as number) < it.opts.length) out[it.id] = v as number;
    else if (it.t === "multi" && Array.isArray(v)) {
      const arr = [...new Set(v.filter((x) => Number.isInteger(x) && x >= 0 && x < it.opts.length))] as number[];
      out[it.id] = arr.sort((a, b) => a - b);
    } else if ((it.t === "short" || it.t === "text") && typeof v === "string") out[it.id] = v.slice(0, 4000);
    else if (it.t === "scale" && typeof v === "object" && !Array.isArray(v)) {
      const o: Record<string, number> = {};
      for (const [k] of it.rows) {
        const x = (v as Record<string, unknown>)[k];
        if (Number.isInteger(x) && (x as number) >= 0 && (x as number) <= 3) o[k] = x as number;
      }
      out[it.id] = o;
    }
  }
  return out;
}
